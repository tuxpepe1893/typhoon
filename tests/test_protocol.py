"""Captured/documented AUX UART frames, independent of our packet builder."""

import pytest

from typhoon.config import DeviceIdentity
from typhoon.controller import make_device, merge_state, public_state
from typhoon.errors import TyphoonError
from typhoon.protocol import TornadoHVAC


@pytest.fixture
def device():
    return make_device(DeviceIdentity("192.0.2.1", "aa:bb:cc:dd:ee:ff"))


@pytest.mark.parametrize("command,expected", [
    (b"\x11\x01", "0c00bb0006800000020011012b7e"),
    (b"\x21\x01", "0c00bb0006800000020021011b7e"),
])
def test_encode_matches_known_aux_queries(device, command, expected):
    # Fixed queries used in makleso6/broadlink-aircon-api, not generated by us.
    assert device._encode(command).hex() == expected


def test_decodes_captured_state_and_validates_checksum(device, monkeypatch):
    # Capture in GrKoR/AUX_HVAC_Protocol, packet_cmd_11_b15: 26 C, cool, iFeel.
    payload = bytes.fromhex("1900bb00070000000f0001119720004000280000200010000066650000000000")
    monkeypatch.setattr(device, "decrypt", lambda _: payload)
    monkeypatch.setattr(device, "send_packet", lambda *_: bytes(56))
    state = device.get_state()
    assert public_state(state)["temperature"] == 26
    assert public_state(state)["mode"] == "cool"
    assert state["ifeel"] is True
    corrupted = bytearray(payload)
    corrupted[12] ^= 1
    monkeypatch.setattr(device, "decrypt", lambda _: corrupted)
    with pytest.raises(TyphoonError, match="checksum"):
        device.get_state()


def test_standard_short_write_ack_is_not_parsed_as_full_state(device, monkeypatch):
    # Command + matching acknowledgement from packet_cmd_01 in protocol docs.
    command_body = bytes.fromhex("97000260002000000000000000")
    assert device._encode(b"\x01\x01" + command_body).hex().endswith("94fd")
    acknowledgement = bytes.fromhex("0e00bb00070000000400010194fda400")
    monkeypatch.setattr(device, "decrypt", lambda _: acknowledgement)
    monkeypatch.setattr(device, "send_packet", lambda *_: bytes(56))
    assert device._send(0, command_body) == bytes.fromhex("94fd")


@pytest.mark.parametrize("mode_byte,name", [(0x00, "auto"), (0x20, "cool"), (0x40, "dry"), (0x80, "heat"), (0xC0, "fan")])
def test_real_mode_codes_decode_and_encode(device, monkeypatch, mode_byte, name):
    raw = bytearray.fromhex("87e00d40002000002000100000")
    raw[5] = mode_byte
    state = device._parse_state(raw)
    assert public_state(state)["mode"] == name
    written = []
    monkeypatch.setattr(device, "_send", lambda command, data: written.append(data) or bytes(2))
    device.set_state(**merge_state(state, {"mode": name}))
    assert written[0][5] >> 5 == mode_byte >> 5


def test_raw_state_bits_survive_an_unrelated_display_change(device, monkeypatch):
    # Timer bits, Fahrenheit flag, arbitrary reserved bytes, power limit.
    raw = bytes.fromhex("83249a520a3b551177aa18e400")
    state = device._parse_state(raw)
    written = []
    monkeypatch.setattr(device, "_send", lambda command, data: written.append(data) or bytes(2))
    device.set_state(**merge_state(state, {"display": True}))
    expected = bytearray(raw)
    expected[10] &= ~0x10
    assert written == [bytes(expected)]


@pytest.mark.parametrize("devtype,initial_wire,initial_visible,command_visible,expected_wire", [
    (0x4E2A, 0, True, False, 1),
    (0x4E2A, 1, False, True, 0),
    (0x4EF9, 0, False, True, 1),
    (0x4EF9, 1, True, False, 0),
])
def test_display_visibility_round_trip_respects_device_profile(
    monkeypatch, devtype, initial_wire, initial_visible, command_visible, expected_wire,
):
    # Exercise the low-level profile without expanding supported app identities.
    device = TornadoHVAC(("192.0.2.1", 80), bytes.fromhex("aabbccddeeff"), devtype)
    raw = bytearray.fromhex("83249a520a3b551177aa08e400")
    raw[10] |= initial_wire << 4
    state = device._parse_state(raw)
    assert public_state(state)["display"] is initial_visible
    sent = []
    monkeypatch.setattr(device, "_send", lambda command, data: sent.append(data) or bytes(2))
    device.set_state(**merge_state(state, {"display": command_visible}))
    expected = bytearray(raw)
    expected[10] = (expected[10] & ~0x10) | (expected_wire << 4)
    assert sent == [bytes(expected)]  # Includes preservation of every unrelated bit.
    readback = device._parse_state(sent[0])
    assert public_state(readback)["display"] is command_visible


def test_unsupported_mode_is_an_explicit_error_before_any_write(device):
    raw = bytearray.fromhex("87e00d40002000002000100000")
    raw[5] = 0x60
    with pytest.raises(TyphoonError, match="unsupported state code") as error:
        device._parse_state(raw)
    assert error.value.details["protocolCodes"]["mode"] == 3
    assert not hasattr(device, "_last_state_payload")


def test_write_requires_a_real_preceding_state_read(device):
    with pytest.raises(TyphoonError, match="Read the current"):
        device.set_state(power=False)


@pytest.mark.parametrize("whole,fraction,expected", [(0x3A, 5, 26.5), (0x41, 2, 33.2), (0x20, 0, 0.0)])
def test_ambient_temperature_does_not_wrap_at_32_degrees(device, monkeypatch, whole, fraction, expected):
    data = bytearray(22)
    data[5], data[21] = whole, fraction
    monkeypatch.setattr(device, "_send", lambda _: data)
    assert device.get_ac_info()["ambient_temp"] == expected
